"""Core schema definitions and types for System-1 Decision Architecture."""

from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import List, Optional, Dict, Any


class DialogueRole(str, Enum):
    """Role identifiers in multi-turn inter-agent dialogues."""
    SYSTEM = "system"
    USER = "user"
    AGENT = "agent"
    TOOL_RETURN = "tool_return"
    PEER_AGENT = "peer_agent"


class AttackCategory(str, Enum):
    """Taxonomy of prompt injection and adversarial attacks in MAS."""
    BENIGN = "benign"
    CRESCENDO_DRIFT = "crescendo_drift"
    INDIRECT_TOOL_POISONING = "indirect_tool_poisoning"
    MIND_VIRUS = "mind_virus"
    SYSTEM_OVERRIDE_EXTRACTION = "system_override_extraction"
    MANY_SHOT_SATURATION = "many_shot_saturation"


class TriageAction(str, Enum):
    """Tri-state dynamic triaging action for System-1 gatekeeper."""
    GREEN = "GREEN"  # Safe / Nominal -> Allow execution
    AMBER = "AMBER"  # Ambiguous / Drift -> Escalate to System-2 Deliberation
    RED = "RED"      # Critical Hazard -> Drop message & Quarantine agent


@dataclass
class DialogueTurn:
    """Individual dialogue turn in an inter-agent interaction sequence."""
    role: DialogueRole
    content: str
    turn_index: int
    is_untrusted: bool = True
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "role": self.role.value if isinstance(self.role, DialogueRole) else self.role,
            "content": self.content,
            "turn_index": self.turn_index,
            "is_untrusted": self.is_untrusted,
            "metadata": self.metadata,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "DialogueTurn":
        return cls(
            role=DialogueRole(data["role"]),
            content=data["content"],
            turn_index=data.get("turn_index", 0),
            is_untrusted=data.get("is_untrusted", True),
            metadata=data.get("metadata", {}),
        )


@dataclass
class TrajectorySample:
    """Multi-turn interaction trajectory containing full history and ground truth."""
    sample_id: str
    system_specification: str
    turns: List[DialogueTurn]
    is_injection: bool
    attack_category: AttackCategory = AttackCategory.BENIGN
    threat_level: str = "nominal"  # nominal, low, moderate, critical
    source_dataset: str = "synthetic"
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "sample_id": self.sample_id,
            "system_specification": self.system_specification,
            "turns": [t.to_dict() for t in self.turns],
            "is_injection": self.is_injection,
            "attack_category": self.attack_category.value if isinstance(self.attack_category, AttackCategory) else self.attack_category,
            "threat_level": self.threat_level,
            "source_dataset": self.source_dataset,
            "metadata": self.metadata,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "TrajectorySample":
        return cls(
            sample_id=data["sample_id"],
            system_specification=data.get("system_specification", ""),
            turns=[DialogueTurn.from_dict(t) for t in data.get("turns", [])],
            is_injection=data.get("is_injection", False),
            attack_category=AttackCategory(data.get("attack_category", "benign")),
            threat_level=data.get("threat_level", "nominal"),
            source_dataset=data.get("source_dataset", "unknown"),
            metadata=data.get("metadata", {}),
        )


@dataclass
class ModelDecision:
    """Decision output generated by a System-1 decision model."""
    threat_probability: float  # Calibrated P(threat in [0.0, 1.0])
    predicted_category: AttackCategory
    latency_ms: float
    action: TriageAction = field(init=False)
    explanation: Optional[str] = None
    category_scores: Dict[str, float] = field(default_factory=dict)

    def __post_init__(self):
        # Tri-state threshold boundaries:
        # P < 0.15 => GREEN (Allow)
        # 0.15 <= P < 0.85 => AMBER (Escalate to System-2 Reasoner)
        # P >= 0.85 => RED (Drop message & Quarantine)
        if self.threat_probability < 0.15:
            self.action = TriageAction.GREEN
        elif self.threat_probability < 0.85:
            self.action = TriageAction.AMBER
        else:
            self.action = TriageAction.RED
